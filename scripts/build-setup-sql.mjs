// Builds the two paste-into-SQL-Editor scripts from migrations/ + seed.sql:
//   supabase/setup.sql            every migration + seed (fresh project)
//   supabase/apply_foundation.sql Spec 01+ migrations + seed (existing project
//                                 that already ran the two original migrations)
// Run: node scripts/build-setup-sql.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'supabase', 'migrations');

/** First migration that belongs to Spec 01 (shared foundation). */
const FOUNDATION_FROM = '20240101000200';

const lf = (text) => text.replace(/\r\n/g, '\n');
const read = (file) => lf(fs.readFileSync(file, 'utf8'));

const migrations = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith('.sql'))
  .sort();

function build(files, header) {
  const parts = files.map((f) => `-- ===== migrations/${f} =====\n${read(path.join(dir, f))}`);
  parts.push(`-- ===== seed.sql =====\n${read(path.join(root, 'supabase', 'seed.sql'))}`);
  return header + parts.join('\n');
}

const setupHeader =
  '-- GENERATED by scripts/build-setup-sql.mjs - do not edit; edit migrations/ or seed.sql instead.\n' +
  '-- Paste into Supabase Dashboard -> SQL Editor -> Run. Safe to re-run (idempotent).\n\n';
fs.writeFileSync(path.join(root, 'supabase', 'setup.sql'), build(migrations, setupHeader));
console.log('Wrote supabase/setup.sql');

const foundation = migrations.filter((f) => f >= FOUNDATION_FROM);
const previous = migrations.filter((f) => f < FOUNDATION_FROM);
const foundationHeader =
  '-- GENERATED by scripts/build-setup-sql.mjs - do not edit; edit migrations/ or seed.sql instead.\n' +
  '-- Applies ONLY the Spec 01 (shared foundation) changes and the DEMO seed to an EXISTING database.\n' +
  `-- Assumes these migrations are already applied: ${previous.join(', ')}.\n` +
  '-- For a brand-new project, run supabase/setup.sql instead.\n' +
  '-- Paste into Supabase Dashboard -> SQL Editor -> Run. Safe to run more than once:\n' +
  '-- it adds missing schema and upserts the seed rows; it never deletes rows.\n\n';
fs.writeFileSync(path.join(root, 'supabase', 'apply_foundation.sql'), build(foundation, foundationHeader));
console.log('Wrote supabase/apply_foundation.sql');
