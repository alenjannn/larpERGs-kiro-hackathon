// Concatenates migrations + seed into supabase/setup.sql so the whole backend
// can be created with ONE paste into the Supabase SQL Editor.
// Run: node scripts/build-setup-sql.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'supabase', 'migrations');
const parts = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith('.sql'))
  .sort()
  .map((f) => `-- ===== migrations/${f} =====\n${fs.readFileSync(path.join(dir, f), 'utf8')}`);
parts.push(`-- ===== seed.sql =====\n${fs.readFileSync(path.join(root, 'supabase', 'seed.sql'), 'utf8')}`);

const header =
  '-- GENERATED by scripts/build-setup-sql.mjs - do not edit; edit migrations/ or seed.sql instead.\n' +
  '-- Paste into Supabase Dashboard -> SQL Editor -> Run. Safe to re-run (idempotent).\n\n';
fs.writeFileSync(path.join(root, 'supabase', 'setup.sql'), header + parts.join('\n'));
console.log('Wrote supabase/setup.sql');
